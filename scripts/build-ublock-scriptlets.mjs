/**
 * Generate the browser-owned uBO scriptlet catalog and content-realm runtime.
 *
 * The upstream scriptlet functions are byte-identical to the pinned uBO
 * revision recorded in argon/adblock/ublock/provenance.json. This script only
 * extracts `fn.toString()` for MAIN-world entries and wraps them in a single
 * classic script that the child actor loads with the content window as its
 * target. It never rewrites the upstream interpreter.
 *
 * Usage: node scripts/build-ublock-scriptlets.mjs
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Effective trust is a property of the complete dependency graph, not just
// the public entry point. Never downgrade a trusted helper through a wrapper.
export function buildScriptletCatalog(scriptlets) {
  const byName = new Map(scriptlets.map(entry => [entry.name, entry]));
  const trust = new Map();
  const visiting = new Set();
  const requiresTrust = entry => {
    if (trust.has(entry.name)) return trust.get(entry.name);
    if (visiting.has(entry.name)) throw new Error(`cyclic scriptlet dependency: ${entry.name}`);
    visiting.add(entry.name);
    const dependencies = (entry.dependencies || []).map(name => {
      const resolved = byName.get(name);
      if (!resolved) throw new Error(`scriptlet ${entry.name} has missing dependency ${name}`);
      if ((entry.world || 'MAIN') === 'MAIN' && (resolved.world || 'MAIN') !== 'MAIN') {
        throw new Error(`MAIN scriptlet ${entry.name} depends on ISOLATED resource ${name}`);
      }
      return requiresTrust(resolved);
    });
    visiting.delete(entry.name);
    const value = entry.requiresTrust === true || dependencies.includes(true);
    trust.set(entry.name, value);
    return value;
  };
  return scriptlets.map(entry => ({
    name: entry.name,
    aliases: Array.isArray(entry.aliases) ? [...entry.aliases] : [],
    dependencies: Array.isArray(entry.dependencies) ? [...entry.dependencies] : [],
    requiresTrust: requiresTrust(entry),
    world: entry.world || 'MAIN',
  }));
}

async function generate() {
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASE = path.join(ROOT, 'argon', 'adblock');
const UBLOCK = path.join(BASE, 'ublock');

const provenance = JSON.parse(fs.readFileSync(path.join(UBLOCK, 'provenance.json'), 'utf8'));
for (const [relative, expected] of Object.entries(provenance.files)) {
  const actual = crypto.createHash('sha256').update(fs.readFileSync(path.join(UBLOCK, relative))).digest('hex');
  if (actual !== expected) {
    throw new Error(`uBO scriptlet source drift: ${relative}`);
  }
}

const { builtinScriptlets } = await import(
  path.join(UBLOCK, 'src', 'js', 'resources', 'scriptlets.js')
);

const catalog = buildScriptletCatalog(builtinScriptlets);
const main = builtinScriptlets.filter(entry => (entry.world || 'MAIN') === 'MAIN');
const byName = new Map(catalog.map(entry => [entry.name, entry]));
for (const entry of main) {
  for (const dependency of entry.dependencies || []) {
    const resolved = byName.get(dependency);
    if (!resolved || resolved.world !== 'MAIN') {
      throw new Error(`MAIN scriptlet ${entry.name} depends on unavailable ${dependency}`);
    }
  }
}

const catalogFile = `// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by scripts/build-ublock-scriptlets.mjs from uBO ${provenance.commit}. Do not edit.
export const SCRIPTLET_COMMIT = ${JSON.stringify(provenance.commit)};
export const SCRIPTLET_CATALOG = ${JSON.stringify(catalog, null, 2)};
`;
fs.writeFileSync(path.join(BASE, 'scriptlet-catalog.mjs'), catalogFile);

const functions = main.map(entry => entry.fn.toString()).join('\n\n');
const callable = main.filter(entry => entry.name.endsWith('.js'));
const registry = callable.map(entry => `[${JSON.stringify(entry.name)}, ${entry.fn.name}],`).join('\n');
const runtimeFile = `// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by scripts/build-ublock-scriptlets.mjs from uBO ${provenance.commit}. Do not edit.
// Complete MAIN-world uBO scriptlet set. Loaded with the content window as the
// scriptloader target, so every function below belongs to the page realm and
// its Function constructor stays subject to the document CSP.
(function uBO_scriptletRuntime() {
'use strict';
const scriptletGlobals = {};
${functions}

const __argonScriptletFunctions = new Map([
${registry}
]);

return function argonScriptletDispatch(selection) {
  if ( Array.isArray(selection) === false ) { return; }
  for ( const item of selection ) {
    if ( item === null || typeof item !== 'object' ) { continue; }
    if ( typeof item.name !== 'string' || Array.isArray(item.args) === false ) { continue; }
    const fn = __argonScriptletFunctions.get(item.name);
    if ( fn === undefined ) { continue; }
    try { fn(...item.args); } catch (e) {}
  }
};
})();
`;
fs.writeFileSync(path.join(BASE, 'scriptlet-runtime.js'), runtimeFile);
console.log(`Generated uBO scriptlet catalog (${catalog.length}) and MAIN runtime (${main.length}) from ${provenance.commit}`);
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  await generate();
}
